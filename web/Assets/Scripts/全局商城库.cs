	public static 商品属性类 获取指定名字的道具(string 道具名)
	{
		int count = 热卖商品列表.Count;
		for (int i = 0; i < count; i++)
		{
			if (热卖商品列表[i].道具名 == 道具名)
			{
				return 热卖商品列表[i];
			}
		}
		count = 特价商品列表.Count;
		for (int j = 0; j < count; j++)
		{
			if (特价商品列表[j].道具名 == 道具名)
			{
				return 特价商品列表[j];
			}
		}
		count = 装备商品列表.Count;
		for (int k = 0; k < count; k++)
		{
			if (装备商品列表[k].道具名 == 道具名)
			{
				return 装备商品列表[k];
			}
		}
		count = 生产商品列表.Count;
		for (int l = 0; l < count; l++)
		{
			if (生产商品列表[l].道具名 == 道具名)
			{
				return 生产商品列表[l];
			}
		}
		count = 加速商品列表.Count;
		for (int m = 0; m < count; m++)
		{
			if (加速商品列表[m].道具名 == 道具名)
			{
				return 加速商品列表[m];
			}
		}
		count = 宝物商品列表.Count;
		for (int n = 0; n < count; n++)
		{
			if (宝物商品列表[n].道具名 == 道具名)
			{
				return 宝物商品列表[n];
			}
		}
		count = 宝箱商品列表.Count;
		for (int num = 0; num < count; num++)
		{
			if (宝箱商品列表[num].道具名 == 道具名)
			{
				return 宝箱商品列表[num];
			}
		}
		count = 其他商品列表.Count;
		for (int num2 = 0; num2 < count; num2++)
		{
			if (其他商品列表[num2].道具名 == 道具名)
			{
				return 其他商品列表[num2];
			}
		}
		return null;
	}
