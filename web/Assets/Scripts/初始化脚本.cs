    public void 初始化驻防将领()
    {
        for (int i = 0; i < 全局变量.所有玩家数据表[2].封地信息表[0].将领信息表.Count; i++)
        {
            int id = (int)全局变量.所有玩家数据表[2].封地信息表[0].将领信息表[i].将领属性.初始属性.ID;
            int index = Random.Range(0, 全局变量.所有城池列表.Count);
            全局变量.所有城池列表[index].城池驻防列表.Add(new 将领索引(2, id));
        }
    }
