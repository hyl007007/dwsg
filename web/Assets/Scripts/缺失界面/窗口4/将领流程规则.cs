    // 原界面操作共用的校验。只修改现有世界对象，不保存第二份库存或编队。
    public static class 将领流程规则
    {
        public static 将领信息 查找将领(玩家数据 玩家, int ID, out 封地信息 所属)
        {
            所属 = null;
            if (玩家 == null || 玩家.封地信息表 == null) return null;
            foreach (var 地 in 玩家.封地信息表)
            {
                if (地 == null || 地.将领信息表 == null) continue;
                foreach (var 将 in 地.将领信息表)
                    if (将 != null && 将.ID == ID) { 所属 = 地; return 将; }
            }
            return null;
        }

        public static 军事结果 检查装备(玩家数据 玩家, 将领装备 装备)
        {
            if (玩家 == null || 玩家.背包装备列表 == null)
                return 军事结果.拒绝(军事错误.无角色, "角色尚未载入。");
            if (装备 == null || 装备.装备信息 == null || 装备.装备信息.名称 == "空")
                return 军事结果.拒绝(军事错误.数量无效, "请先选择装备。");
            bool 找到 = false;
            for (int i = 0; i < 4; i++)
            {
                var 表 = 玩家.背包装备列表.获取指定部位列表(i);
                if (表 != null && 表.Contains(装备)) 找到 = true;
            }
            if (!找到) return 军事结果.拒绝(军事错误.数量无效, "装备已变更，请重新选择。");
            if (!军事本地规则.有限(装备.品质) || 装备.品质 < 1 || 装备.品质 > 4 ||
                装备.品质 != Math.Floor(装备.品质) || !军事本地规则.有限(装备.强化等级) ||
                装备.强化等级 < 0 || 装备.强化等级 > 30 || 装备.强化等级 != Math.Floor(装备.强化等级))
                return 军事结果.拒绝(军事错误.数量无效, "装备数据无效。");
            if (装备.将领ID != -1)
            {
                封地信息 地;
                var 将 = 查找将领(玩家, 装备.将领ID, out 地);
                var 检查 = 军事本地规则.检查将领(玩家, 地, 将);
                if (!检查.成功) return 检查;
            }
            return 军事结果.通过("装备可操作。");
        }

        public static 军事结果 穿戴(玩家数据 玩家, 封地信息 地, 将领信息 将, int 部位, 将领装备 装备)
        {
            var 检查 = 军事本地规则.检查将领(玩家, 地, 将);
            if (!检查.成功) return 检查;
            检查 = 检查装备(玩家, 装备);
            if (!检查.成功) return 检查;
            var 表 = 玩家.背包装备列表.获取指定部位列表(部位);
            if (表 == null || !表.Contains(装备)) return 军事结果.拒绝(军事错误.数量无效, "装备部位不符。");
            if (装备.将领ID != -1) return 军事结果.拒绝(军事错误.状态冲突, "装备已被穿戴，请重新选择。");
            if (将.将领属性.成长点数 == null || !军事本地规则.有限(装备.获取装备等级()) ||
                !军事本地规则.有限(将.将领属性.成长点数.等级) || 将.将领属性.成长点数.等级 < 装备.获取装备等级())
                return 军事结果.拒绝(军事错误.达到上限, "将领等级不足，未更换装备。");
            foreach (var 旧 in 表)
                if (旧 != null && 旧.将领ID == 将.ID) 旧.将领ID = -1;
            装备.将领ID = 将.ID;
            return 军事结果.通过("穿戴成功。");
        }

        public static void 更新装备属性(玩家数据 玩家, 封地信息 地, 将领信息 将)
        {
            军事本地规则.计算属性保留体力(玩家);
            if (将 == null || 将.将领配兵 == null || 将.将领属性 == null || 将.将领属性.最终属性 == null) return;
            double 上限 = Math.Floor(Math.Max(0, 将.将领属性.最终属性.统兵));
            if (军事本地规则.有限(上限) && 上限 <= int.MaxValue && 将.将领配兵.数量 > 上限)
                军事本地规则.配兵(玩家, 地, 将, (int)将.将领配兵.ID, (int)上限);
        }

        // 先规划每堆扣除量，再统一扣款；黄金/锁定材料不足时不扣任何材料。
        public static 军事结果 支付材料(玩家数据 玩家, Dictionary<string, int> 材料, double 黄金 = 0)
        {
            if (玩家 == null || 玩家.背包道具列表 == null || 玩家.财产信息 == null)
                return 军事结果.拒绝(军事错误.无角色, "角色尚未载入。");
            if (!军事本地规则.有限(黄金) || 黄金 < 0 || 材料 == null)
                return 军事结果.拒绝(军事错误.数量无效, "消耗数量无效。");
            if (!军事本地规则.有限(玩家.财产信息.黄金) || 玩家.财产信息.黄金 < 黄金)
                return 军事结果.拒绝(军事错误.资源不足, "黄金不足，需要" + 黄金.ToString("0") + "黄金。");
            var 扣除表 = new Dictionary<道具信息, int>();
            var 分类 = new[] { 玩家.背包道具列表.宝物道具列表, 玩家.背包道具列表.加速道具列表,
                玩家.背包道具列表.生产道具列表, 玩家.背包道具列表.宝箱道具列表,
                玩家.背包道具列表.强化道具列表, 玩家.背包道具列表.任务道具列表 };
            foreach (var 项 in 材料)
            {
                if (string.IsNullOrEmpty(项.Key) || 项.Value < 0)
                    return 军事结果.拒绝(军事错误.数量无效, "消耗数量无效。");
                int 待扣 = 项.Value;
                var 已检查 = new HashSet<道具信息>();
                foreach (var 表 in 分类)
                {
                    if (表 == null) continue;
                    foreach (var 道具 in 表)
                    {
                        if (道具 == null || 道具.名字 != 项.Key || !已检查.Add(道具)) continue;
                        if (!军事本地规则.有限(道具.数量) || 道具.数量 < 0 || 道具.数量 != Math.Floor(道具.数量))
                            return 军事结果.拒绝(军事错误.数量无效, "材料库存无效，未扣除材料。");
                        int 扣 = (int)Math.Min(待扣, 道具.数量);
                        if (扣 > 0) { 扣除表[道具] = 扣; 待扣 -= 扣; }
                    }
                }
                if (待扣 > 0) return 军事结果.拒绝(军事错误.资源不足, 项.Key + "不足，需要" + 项.Value + "个。");
            }
            foreach (var 项 in 扣除表) 项.Key.数量 -= 项.Value;
            foreach (var 表 in 分类)
                if (表 != null) 表.RemoveAll(x => x != null && 扣除表.ContainsKey(x) && x.数量 == 0);
            玩家.财产信息.黄金 -= 黄金;
            return 军事结果.通过("材料已扣除。");
        }

        public static 军事结果 支付炼魂(玩家数据 玩家, 将领装备 装备, bool 高级, bool 玉石)
        {
            var 检查 = 检查装备(玩家, 装备);
            if (!检查.成功) return 检查;
            if (玉石) return 军事结果.拒绝(军事错误.未接入, "当前没有玉石材料，请选择普通或黄金炼魂。");
            int 锁定 = 0;
            if (装备.炼魂属性 != null)
                foreach (var 魂 in 装备.炼魂属性) if (魂 != null && 魂.锁定) 锁定++;
            if (锁定 >= 6) return 军事结果.拒绝(军事错误.达到上限, "六条属性均已锁定，请先解锁一条。");
            return 支付材料(玩家, new Dictionary<string, int> {
                { 装备.获取装备炼魂材料名字(), (int)装备.品质 }, { "凝魂晶石", 锁定 } }, 高级 ? 5 : 0);
        }

        public static void 补齐编队(玩家数据 玩家)
        {
            if (玩家 == null) return;
            if (玩家.编队信息表 == null) 玩家.编队信息表 = new List<List<int>>();
            while (玩家.编队信息表.Count < 5) 玩家.编队信息表.Add(new List<int>());
            for (int i = 0; i < 5; i++)
            {
                if (玩家.编队信息表[i] == null) 玩家.编队信息表[i] = new List<int>();
                while (玩家.编队信息表[i].Count < 5) 玩家.编队信息表[i].Add(-1);
            }
        }

        public static 军事结果 改名(玩家数据 玩家, 封地信息 地, 将领信息 将, string 名字)
        {
            var 检查 = 军事本地规则.检查将领(玩家, 地, 将);
            if (!检查.成功) return 检查;
            if (将.将领属性.初始属性.系列 == "名将")
                return 军事结果.拒绝(军事错误.状态冲突, "名将不可改名。");
            名字 = (名字 ?? "").Trim();
            if (名字.Length == 0) return 军事结果.拒绝(军事错误.数量无效, "名字不能为空。");
            foreach (char 字 in 名字)
                if (char.IsControl(字)) return 军事结果.拒绝(军事错误.数量无效, "名字不能包含换行或控制字符。");
            将.将领属性.初始属性.名字 = 名字;
            return 军事结果.通过("改名成功。");
        }

        public static 军事结果 加入编队(玩家数据 玩家, 封地信息 地, 将领信息 将, int 队, int 槽 = -1)
        {
            var 检查 = 军事本地规则.检查将领(玩家, 地, 将);
            if (!检查.成功) return 检查;
            if (队 < 0 || 队 >= 5 || 槽 < -1 || 槽 >= 5)
                return 军事结果.拒绝(军事错误.数量无效, "请先选择编队。");
            补齐编队(玩家);
            for (int i = 0; i < 5; i++)
                for (int j = 0; j < 5; j++)
                    if (玩家.编队信息表[i][j] == 将.ID)
                        return 军事结果.拒绝(军事错误.状态冲突, "将领已在第" + (i + 1) + "编队，请先移出。");
            if (槽 == -1)
                for (int i = 0; i < 5; i++) if (玩家.编队信息表[队][i] == -1) { 槽 = i; break; }
            if (槽 == -1 || 玩家.编队信息表[队][槽] != -1)
                return 军事结果.拒绝(军事错误.达到上限, "编队已满，每队最多5名将领。");
            玩家.编队信息表[队][槽] = 将.ID;
            将.详细信息.编队 = 队 + 1;
            return 军事结果.通过("已加入第" + (队 + 1) + "编队。");
        }

        public static 军事结果 移出编队(玩家数据 玩家, int 队, int 槽)
        {
            if (玩家 == null) return 军事结果.拒绝(军事错误.无角色, "角色尚未载入。");
            if (队 < 0 || 队 >= 5 || 槽 < 0 || 槽 >= 5)
                return 军事结果.拒绝(军事错误.数量无效, "请选择编队中的将领。");
            补齐编队(玩家);
            封地信息 地;
            var 将 = 查找将领(玩家, 玩家.编队信息表[队][槽], out 地);
            if (将 != null)
            {
                var 检查 = 军事本地规则.检查将领(玩家, 地, 将);
                if (!检查.成功) return 检查;
                将.详细信息.编队 = 0;
            }
            玩家.编队信息表[队][槽] = -1;
            return 军事结果.通过("已移出编队。");
        }
