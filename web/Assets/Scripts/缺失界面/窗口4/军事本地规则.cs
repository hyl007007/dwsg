using System;
using System.Collections.Generic;
using 玩家数据结构;

namespace 缺失界面.窗口4
{
    public enum 军事错误 { 无, 无角色, 无封地, 无将领, 状态冲突, 数量无效, 兵力不足, 资源不足, 达到上限, 未接入 }

    public sealed class 军事结果
    {
        public 军事错误 错误;
        public string 说明;
        public bool 成功 { get { return 错误 == 军事错误.无; } }
        public static 军事结果 通过(string 说明) { return new 军事结果 { 说明 = 说明 }; }
        public static 军事结果 拒绝(军事错误 错误, string 说明) { return new 军事结果 { 错误 = 错误, 说明 = 说明 }; }
    }

    // 本地适配规则；不代表原版手游数值，不发送网络命令。
    // 只改既有将领/库存字段，随现有世界 JSON 保存，无独立文件或第二份世界状态。
    public static class 军事本地规则
    {
        public const int 修炼体力 = 10;
        public static bool 有限(double 值) { return !double.IsNaN(值) && !double.IsInfinity(值); }

        public static 军事结果 检查将领(玩家数据 玩家, 封地信息 封地, 将领信息 将领)
        {
            if (玩家 == null) return 军事结果.拒绝(军事错误.无角色, "本地角色尚未载入。");
            if (封地 == null || 玩家.封地信息表 == null || !玩家.封地信息表.Contains(封地))
                return 军事结果.拒绝(军事错误.无封地, "封地已变更，请重新选择。");
            if (将领 == null || 封地.将领信息表 == null || !封地.将领信息表.Contains(将领) ||
                将领.详细信息 == null || 将领.将领属性 == null || 将领.将领配兵 == null)
                return 军事结果.拒绝(军事错误.无将领, "将领已变更，请重新选择。");
            if (将领.详细信息.状态 != 0)
                return 军事结果.拒绝(军事错误.状态冲突, "仅空闲将领可操作；出征、驻防或被俘将领不能修炼、恢复或配兵。");
            return 军事结果.通过("将领空闲");
        }

        public static double 闲兵数量(封地信息 封地, int 兵种)
        {
            double 数量 = 0;
            if (封地 == null || 封地.闲兵信息表 == null) return 0;
            foreach (var 兵 in 封地.闲兵信息表)
                if (兵.ID == 兵种 && 有限(兵.数量) && 兵.数量 > 0) 数量 += 兵.数量;
            return 数量;
        }

        public static 军事结果 配兵(玩家数据 玩家, 封地信息 封地, 将领信息 将领, int 兵种, int 目标数量)
        {
            var 检查 = 检查将领(玩家, 封地, 将领);
            if (!检查.成功) return 检查;
            var 旧 = 将领.将领配兵;
            if (封地.闲兵信息表 == null || 将领.将领属性.最终属性 == null ||
                !有限(旧.数量) || 旧.数量 < 0 || !有限(将领.将领属性.最终属性.统兵))
                return 军事结果.拒绝(军事错误.数量无效, "配兵数据无效，请重新载入存档。");
            if (目标数量 < 0 || (目标数量 > 0 && 兵种 <= 0))
                return 军事结果.拒绝(军事错误.数量无效, "配兵数量必须为非负整数。");
            if (目标数量 > Math.Floor(Math.Max(0, 将领.将领属性.最终属性.统兵)))
                return 军事结果.拒绝(军事错误.达到上限, "目标数量超过将领统兵上限。");
            if (旧.数量 > 0 && (!有限(旧.ID) || 旧.ID <= 0 || 旧.ID != Math.Floor(旧.ID)))
                return 军事结果.拒绝(军事错误.数量无效, "当前兵种无效，未转移任何士兵。");
            foreach (var 兵 in 封地.闲兵信息表)
                if ((兵.ID == 兵种 || 兵.ID == 旧.ID) && (!有限(兵.数量) || 兵.数量 < 0))
                    return 军事结果.拒绝(军事错误.数量无效, "闲兵数据无效，未调整部队。");
            double 可用 = 闲兵数量(封地, 兵种) + (旧.ID == 兵种 ? 旧.数量 : 0);
            if (目标数量 > 可用)
                return 军事结果.拒绝(军事错误.兵力不足, "本封地闲兵不足，未调整部队。");
            if ((目标数量 == 0 && 旧.数量 == 0) || (旧.ID == 兵种 && 旧.数量 == 目标数量))
                return 军事结果.通过("配兵数量未变化。");

            // 全部校验通过后再转移；相同目标重复提交不会重复消耗。
            if (旧.数量 > 0) 封地.添加闲兵((int)旧.ID, 旧.数量);
            double 待扣 = 目标数量;
            for (int i = 封地.闲兵信息表.Count - 1; i >= 0 && 待扣 > 0; i--)
            {
                var 兵 = 封地.闲兵信息表[i];
                if (兵.ID != 兵种 || 兵.数量 <= 0) continue;
                double 扣除 = Math.Min(兵.数量, 待扣);
                兵.数量 -= 扣除;
                待扣 -= 扣除;
                if (兵.数量 <= 0) 封地.闲兵信息表.RemoveAt(i);
            }
            旧.ID = 目标数量 == 0 ? 0 : 兵种;
            旧.数量 = 目标数量;
            将领.详细信息.剩余兵力 = 目标数量;
            return 军事结果.通过(目标数量 == 0 ? "部队已归还本封地闲兵。" : "配兵完成：" + 目标数量 + "名士兵。");
        }

        public static double 修炼费用(将领信息 将领) { return Math.Max(1, 将领.将领属性.成长点数.等级) * 100; }
        public static double 修炼经验(将领信息 将领)
        {
            return Math.Ceiling(将领.获取当前等级升级需要经验(将领.将领属性.成长点数.等级) / 10);
        }

        public static 军事结果 修炼(玩家数据 玩家, 封地信息 封地, 将领信息 将领)
        {
            var 检查 = 检查将领(玩家, 封地, 将领);
            if (!检查.成功) return 检查;
            double 等级 = 将领.将领属性.成长点数.等级;
            if (!有限(等级) || 等级 < 1 || !有限(将领.详细信息.经验) ||
                !有限(将领.详细信息.剩余体力) || 玩家.财产信息 == null || !有限(玩家.财产信息.铜钱))
                return 军事结果.拒绝(军事错误.数量无效, "将领或铜钱数据无效。");
            if (等级 >= 99) return 军事结果.拒绝(军事错误.达到上限, "将领已达到99级。");
            double 费用 = 修炼费用(将领);
            if (将领.详细信息.剩余体力 < 修炼体力)
                return 军事结果.拒绝(军事错误.资源不足, "体力不足10点，可使用活血丹恢复。");
            if (玩家.财产信息.铜钱 < 费用)
                return 军事结果.拒绝(军事错误.资源不足, "铜钱不足，需要" + 费用 + "铜钱。");
            double 经验 = 修炼经验(将领);
            玩家.财产信息.铜钱 -= 费用;
            将领.详细信息.剩余体力 -= 修炼体力;
            将领.将领获取经验值(经验);
            return 军事结果.通过("修炼完成：经验+" + 经验 + "，体力-10，铜钱-" + 费用 + "。");
        }

        public static 军事结果 恢复体力(玩家数据 玩家, 封地信息 封地, 将领信息 将领)
        {
            var 检查 = 检查将领(玩家, 封地, 将领);
            if (!检查.成功) return 检查;
            double 上限 = 将领.将领属性.最终属性.体力上限;
            if (!有限(上限) || 上限 <= 0 || !有限(将领.详细信息.剩余体力) || 将领.详细信息.剩余体力 < 0)
                return 军事结果.拒绝(军事错误.数量无效, "体力数据无效。");
            if (将领.详细信息.剩余体力 >= 上限)
                return 军事结果.拒绝(军事错误.达到上限, "体力已满，不消耗道具。");
            if (玩家.背包道具列表 == null || !玩家.背包道具列表.扣除道具("活血丹", 1))
                return 军事结果.拒绝(军事错误.资源不足, "背包没有活血丹，请先获得该道具。");
            double 恢复 = Math.Min(50, 上限 - 将领.详细信息.剩余体力);
            将领.详细信息.剩余体力 += 恢复;
            return 军事结果.通过("使用活血丹1个，体力+" + 恢复 + "。");
        }

        public static 军事结果 检查出征(玩家数据 玩家, List<将领信息> 将领表)
        {
            if (玩家 == null) return 军事结果.拒绝(军事错误.无角色, "角色尚未载入。");
            if (将领表 == null || 将领表.Count == 0) return 军事结果.拒绝(军事错误.无将领, "请先选择出征将领。");
            if (将领表.Count > 5) return 军事结果.拒绝(军事错误.达到上限, "每次最多出征5名将领。");
            var 已选 = new HashSet<将领信息>();
            foreach (var 将领 in 将领表)
            {
                封地信息 所属 = null;
                foreach (var 封地 in 玩家.封地信息表)
                    if (封地.将领信息表.Contains(将领)) { 所属 = 封地; break; }
                var 检查 = 检查将领(玩家, 所属, 将领);
                if (!检查.成功) return 检查;
                if (!已选.Add(将领)) return 军事结果.拒绝(军事错误.状态冲突, "不能重复派遣同一将领。");
                if (!有限(将领.将领配兵.数量) || 将领.将领配兵.数量 <= 0 || 将领.将领配兵.ID <= 0)
                    return 军事结果.拒绝(军事错误.兵力不足, "所选将领需要先配兵。");
                if (!有限(将领.详细信息.剩余体力) || 将领.详细信息.剩余体力 < 5)
                    return 军事结果.拒绝(军事错误.资源不足, "所选将领体力不足5点。");
            }
            return 军事结果.通过("可出征");
        }

        public static void 计算属性保留体力(玩家数据 玩家)
        {
            if (玩家 == null || 玩家.封地信息表 == null) return;
            var 体力表 = new Dictionary<将领信息, double>();
            foreach (var 封地 in 玩家.封地信息表)
                foreach (var 将领 in 封地.将领信息表)
                    if (将领 != null && 将领.详细信息 != null) 体力表[将领] = 将领.详细信息.剩余体力;
            玩家.计算最终属性();
            foreach (var 条目 in 体力表)
                条目.Key.详细信息.剩余体力 = Math.Min(Math.Max(0, 条目.Value), Math.Max(0, 条目.Key.将领属性.最终属性.体力上限));
        }
    }
