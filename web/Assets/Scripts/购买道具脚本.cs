    public void 打开购买界面()
	{
		base.gameObject.SetActive(value: true);
	}

	public void 改变购买数量()
	{
		购买数量对象.text = 数量滑条对象.value.ToString();
		购买数量 = 数量滑条对象.value;
	}

	public void 刷新商城显示()
	{
		if (商城界面对象.activeSelf)
		{
			商城界面对象.GetComponent<显示商城列表>().刷新显示();
		}
	}
