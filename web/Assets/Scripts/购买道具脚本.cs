        print(道具数量);
		if (道具数量>=购买数量)
		{
            
			double 剩余道具数量 = 道具数量- 购买数量;
            全局变量.所有玩家数据表[全局变量.本机身份].背包道具列表.删除道具(道具名字);
			if(剩余道具数量>0)
				全局变量.所有玩家数据表[全局变量.本机身份].背包道具列表.添加道具(道具名字, (int)剩余道具数量);
			全局变量.所有玩家数据表[全局变量.本机身份].财产信息.黄金 += 商品属性类.黄金售价 * 购买数量;
